#!/usr/bin/env node
// Nextra builds its "On This Page" TOC by statically parsing literal `##`/`###`
// headings in each .mdx file at compile time — it has no way to see headings
// rendered later by a React component from runtime-fetched data. The old
// <ReleaseNotes /> component rendered current versions from JSON at request
// time, so the page body updated on every release but the TOC sidebar never
// picked up the new version headings.
//
// This script renders the same release notes as literal MDX ahead of `next
// build`, so Nextra's heading parser sees them like any other static section.

import { writeFile, mkdir, readFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')

const SOURCE_URL =
  process.env.NEXT_PUBLIC_RELEASE_NOTES_URL ||
  'https://raw.githubusercontent.com/ZentroIDE/Zentro/main/release-notes/index.json'

// Deliberately outside pages/ — anything under pages/ becomes its own routable
// page in Next.js, and we only want this imported as a partial, not served at
// /changelog/_release-notes.generated.
const OUTPUT_PATH = join(ROOT, 'content', 'changelog-release-notes.generated.mdx')

function isReleaseNoteArray(data) {
  return (
    Array.isArray(data) &&
    data.length > 0 &&
    data.every((d) => d && typeof d === 'object' && typeof d.version === 'string' && typeof d.body === 'string')
  )
}

async function fetchReleaseNotes() {
  try {
    const controller = new AbortController()
    const timeout = setTimeout(() => controller.abort(), 8000)
    const res = await fetch(SOURCE_URL, { signal: controller.signal })
    clearTimeout(timeout)
    if (res.ok) {
      const data = await res.json()
      if (isReleaseNoteArray(data)) return data
    }
    console.warn(`[generate-release-notes-mdx] unexpected response from ${SOURCE_URL}; using local snapshot`)
  } catch (err) {
    console.warn(`[generate-release-notes-mdx] fetch failed (${String(err)}); using local snapshot`)
  }
  const fallbackPath = join(ROOT, 'data', 'release-notes.json')
  return JSON.parse(await readFile(fallbackPath, 'utf8'))
}

function formatDate(date) {
  if (!date) return ''
  const dt = new Date(`${date}T00:00:00Z`)
  if (Number.isNaN(dt.getTime())) return date
  return dt.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric', timeZone: 'UTC' })
}

function renderNote(note) {
  const date = formatDate(note.date)
  const heading = `## ${note.tag}${date ? ` — ${date}` : ''}${note.prerelease ? ' (pre-release)' : ''}`
  const highlights = note.highlights ? `**Highlights**: ${note.highlights}\n\n` : ''
  return `${heading}\n\n${highlights}${note.body.trim()}\n`
}

async function main() {
  const releases = await fetchReleaseNotes()
  const body = releases.map(renderNote).join('\n---\n\n')
  const contents = `{/* Generated by scripts/generate-release-notes-mdx.mjs — do not edit by hand.\n   Regenerated on every \`npm run build\` / \`npm run dev\` from the source in\n   lib/releaseNotes.ts's fetch target, falling back to data/release-notes.json. */}\n\n${body}\n`
  await mkdir(dirname(OUTPUT_PATH), { recursive: true })
  await writeFile(OUTPUT_PATH, contents, 'utf8')
  console.log(`[generate-release-notes-mdx] wrote ${releases.length} release(s) to ${OUTPUT_PATH}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
